"""The plan catalog as the plan-limit tests read it (mcp-conversion D-14, doc 07 §6.1).

Tests are generated from ``libs/platform_auth/plans.yaml``, never from a
literal "Trader and Pro": every expected plan list here is computed from the
catalog the way keel-api's ``pricing.higher_plan_limits`` computes it (catalog
paid rows, in ladder order, whose declared value beats the caller's), so a
renamed, added or re-limited plan moves the expectations with it. One golden
(the Free wall, test_errors) pins the exact rendering, and the shared
``libs/platform_auth/fixtures/limit_copy_cases.json`` (generated by
``platform_auth.limit_copy`` from plans.yaml) pins the SDK renderer to the
libs one.

The SDK's own venv has no ``platform_auth`` (sdk-test.yml runs without
``PYTHONPATH=libs``), so the comparison is restated here over the YAML: v2
consumables all meter per 30 days, so declared limits compare directly.
"""

from __future__ import annotations

import json
import math
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

import yaml


REPO_ROOT = Path(__file__).resolve().parents[4]
PLANS_YAML = REPO_ROOT / "libs" / "platform_auth" / "plans.yaml"
SHARED_CASES = REPO_ROOT / "libs" / "platform_auth" / "fixtures" / "limit_copy_cases.json"

#: The floor attr every catalog plan declares (plans.yaml `attrs`).
FLOOR_ATTR = "paper_live_clock_floor"


@lru_cache(maxsize=1)
def catalog() -> dict[str, Any]:
    return yaml.safe_load(PLANS_YAML.read_text())


def units() -> dict[str, dict[str, Any]]:
    return catalog()["units"]


def paid_rows() -> list[tuple[str, str]]:
    return [(row["plan"], row["version"]) for row in catalog()["catalog"]["paid"]]


def _version(version: str) -> dict[str, Any]:
    return catalog()["versions"][version]


def display_name(plan: str, version: str = "v2") -> str:
    """The catalog's display name: an optional ``attrs.<plan>.display_name``,
    else the capitalised id (doc 07 §6.1)."""
    attrs = (_version(version).get("attrs") or {}).get(plan) or {}
    name = attrs.get("display_name")
    return name if isinstance(name, str) and name else plan.capitalize()


def _value(plan: str, version: str, unit: str) -> float:
    block = (_version(version)["plans"].get(plan) or {}).get(unit)
    if block is True:
        return 1
    if not isinstance(block, dict):
        return 0  # undeclared (or false) reads as none
    limit = block.get("limit")
    return math.inf if limit == "unlimited" else float(limit)


def higher_plans(plan: str, unit: str, version: str = "v2") -> list[dict[str, str]]:
    """The served ``higher_plans`` for ``plan`` on ``unit`` (names only)."""
    ours = _value(plan, version, unit)
    out = []
    for row_plan, row_version in paid_rows():
        if _value(row_plan, row_version, unit) > ours:
            out.append({"plan": row_plan, "version": row_version, "name": display_name(row_plan)})
    return out


_CLOCK = re.compile(r"^(\d+)(min|h|d)$")


def _minutes(clock: str) -> int:
    n, unit = _CLOCK.match(clock).groups()
    return int(n) * {"min": 1, "h": 60, "d": 1440}[unit]


def floor_of(plan: str, version: str = "v2") -> str:
    return (_version(version)["attrs"][plan])[FLOOR_ATTR]


def faster_plans(plan: str, version: str = "v2") -> list[dict[str, str]]:
    """The served ``higher_plans`` on the paper/live timeframe floor."""
    ours = _minutes(floor_of(plan, version))
    out = []
    for row_plan, row_version in paid_rows():
        attrs = (_version(row_version).get("attrs") or {}).get(row_plan) or {}
        theirs = attrs.get(FLOOR_ATTR)
        if isinstance(theirs, str) and _minutes(theirs) < ours:
            out.append({"plan": row_plan, "version": row_version, "name": display_name(row_plan)})
    return out


def names(entries: list[dict[str, str]]) -> list[str]:
    return [e["name"] for e in entries]


def all_plan_names() -> list[str]:
    """Every plan display name the catalog (any version) could serve."""
    found: list[str] = []
    blocks = [catalog().get("plans") or {}, *(v["plans"] for v in catalog()["versions"].values())]
    for plans in blocks:
        for plan in plans:
            if plan in ("anon", "internal", "app"):
                continue  # not Keel product plans a customer is told about
            name = display_name(plan)
            if name not in found:
                found.append(name)
    return found


def limit_copy_cases() -> dict[str, Any]:
    """The shared parity table (doc 07 §6.2), as platform_auth generates it."""
    return json.loads(SHARED_CASES.read_text())
